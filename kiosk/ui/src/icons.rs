/// Icône de secours (une tasse) pour un nom inconnu.
pub const FALLBACK: Rows = ICONS[ICONS.len() - 1].1;

pub fn builtin(name: &str) -> Option<Rows> {
    ICONS.iter().find(|(n, _)| *n == name).map(|(_, rows)| *rows)
}

pub fn names() -> Vec<&'static str> {
    ICONS.iter().map(|(name, _)| *name).collect()
}

/// Taille maximale d'un dessin, en points de côté.
pub const MAX_SIZE: usize = 32;

/// Vérifie un dessin : lignes de même longueur, seulement `#` et `.`, au plus 32 × 32.
pub fn check<S: AsRef<str>>(rows: &[S]) -> Result<(), String> {
    let width = rows.first().map_or(0, |r| r.as_ref().len());
    if rows.is_empty() || width == 0 {
        return Err("dessin vide".into());
    }
    if rows.len() > MAX_SIZE || width > MAX_SIZE {
        return Err(format!("au plus {MAX_SIZE} × {MAX_SIZE} points"));
    }
    for (i, row) in rows.iter().enumerate() {
        let row = row.as_ref();
        if row.len() != width {
            return Err(format!("la ligne {} n'a pas la même longueur que la première", i + 1));
        }
        if !row.bytes().all(|b| b == b'#' || b == b'.') {
            return Err(format!("la ligne {} contient autre chose que `#` et `.`", i + 1));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builtin_icons_are_16_by_16() {
        for (name, rows) in ICONS {
            assert_eq!(rows.len(), 16, "{name}");
            assert!(rows.iter().all(|r| r.len() == 16), "{name}");
            check(rows).unwrap_or_else(|e| panic!("{name} : {e}"));
        }
    }

    #[test]
    fn rejects_bad_drawings() {
        assert!(check::<&str>(&[]).is_err());
        assert!(check(&["##", "#"]).is_err());
        assert!(check(&["#x"]).is_err());
    }
}
